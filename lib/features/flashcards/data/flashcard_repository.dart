  static List<FlashcardItem> getCardsByCategory(String category) {
    if (category == 'All') return allCards;
    return allCards.where((c) => c.category == category).toList();
  }

  static List<FlashcardItem> searchCards(String query) {
    final clean = query.trim().toLowerCase();
    if (clean.isEmpty) return allCards;
    return allCards.where((c) {
      return c.hindi.toLowerCase().contains(clean) ||
          c.santhaliDev.toLowerCase().contains(clean) ||
          c.santhali.toLowerCase().contains(clean) ||
          c.santhaliLatin.toLowerCase().contains(clean) ||
          c.ho.toLowerCase().contains(clean) ||
          c.mundari.toLowerCase().contains(clean) ||
          c.englishMeaning.toLowerCase().contains(clean) ||
          c.categoryLabel.toLowerCase().contains(clean);
    }).toList();
  }
